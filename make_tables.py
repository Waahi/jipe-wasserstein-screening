def circ_blocks(n, Lb, rng):
    idx = []
    while len(idx) < n:
        s = int(rng.integers(0, n))
        idx.extend([(s + j) % n for j in range(Lb)])
    return idx[:n]


def block_ci(x, B=6000, Lb=4, seed=20250724):
    x = np.asarray([v for v in x if v is not None], float)
    x = x[~np.isnan(x)]
    rng = np.random.default_rng(seed)
    n = len(x)
    bs = np.empty(B)
    for b in range(B):
        bs[b] = x[circ_blocks(n, Lb, rng)].mean()
    return float(x.mean()), float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5)), n


